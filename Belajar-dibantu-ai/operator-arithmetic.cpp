#include <iostream>

using namespace std;

int main() {

    int a = 20;
    int b = 6;

    cout << "===== OPERATOR ARITMATIKA =====" << endl;

    // Penjumlahan
    cout << "a + b = " << a + b << endl;

    // Pengurangan
    cout << "a - b = " << a - b << endl;

    // Perkalian
    cout << "a * b = " << a * b << endl;

    // Pembagian
    cout << "a / b = " << a / b << endl;

    // Modulus / sisa pembagian
    cout << "a % b = " << a % b << endl;


    return 0;
}