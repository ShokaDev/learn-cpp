#include <iostream>

using namespace std;

int main() {

    int a = 20;
    int b = 6;

    cout << "===== OPERATOR PERBANDINGAN =====" << endl;

    // Sama dengan
    cout << "a == b : " << (a == b) << endl;

    // Tidak sama dengan
    cout << "a != b : " << (a != b) << endl;

    // Lebih besar
    cout << "a > b  : " << (a > b) << endl;

    // Lebih kecil
    cout << "a < b  : " << (a < b) << endl;

    // Lebih besar atau sama dengan
    cout << "a >= b : " << (a >= b) << endl;

    // Lebih kecil atau sama dengan
    cout << "a <= b : " << (a <= b) << endl;

    return 0;
}