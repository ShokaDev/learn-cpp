#include <iostream>

using namespace std;

int main() {
    int x = 10; // Nilai X
    int y = 6; // Nilai Y

    int umurA = 32; // Umur A
    int umurB = 32; // Umur B

    cout << "X > Y = " << (x > y) << endl; // Lebih besar
    cout << "X < Y = " << (x < y) << endl; // Lebih kecil
    cout << "X >= Y = " << (x >= y) << endl; // Lebih besar sama dengan
    cout << "X <= Y = " << (x <= y) << endl; // Lebih kecil sama dengan

    cout << "UmurA == UmurB = " << (umurA == umurB) << endl; // Sama dengan
    cout << "UmurA =!= UmurB = " << (umurA != umurB) << endl; // Tidak sama dengan
}