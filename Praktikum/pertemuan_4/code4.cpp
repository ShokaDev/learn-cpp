#include <iostream>

using namespace std;

int main () {
    int m = 55; // Nilai awal m
    int n = 55; // Nilai awal n

    cout << "m awal = " << m << endl; //Menampilan nilai awal m
    m++;
    cout << "m setelah increment = " << m << endl; // Menampilkan nilai m setelah ditambah

    cout << "n awal = " << n << endl; //Menampilan nilai awal m
    m++;
    cout << "n setelah increment = " << n << endl; // Menampilkan nilai m setelah ditambah

    return 0;
}